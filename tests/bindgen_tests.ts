// ── 5. generateBindings — math interface ─────────────────────────────────────

function testGenBindingsMath() {
  console.log(yellow(bold("\n── generateBindings — math module")));

  const wit = `package local:math-50;
world math-50 {
  export add: func(a: s32, b: s32) -> s32;
  export multiply: func(a: f64, b: f64) -> f64;
  export square: func(x: s32) -> s32;
}
`;
  const ts = generateBindings(wit);
  ok("has auto-generated comment", ts.includes("auto-generated by wasmtk bindgen"));
  contains("exports ModuleExports", ts, "export interface ModuleExports {");
  contains("add signature", ts, "add(a: number, b: number): number;");
  contains("multiply signature", ts, "multiply(a: number, b: number): number;");
  contains("square signature", ts, "square(x: number): number;");
  contains("loadModule exported", ts, "export async function loadModule(");
  ok("no ModuleImports (no imports)", !ts.includes("ModuleImports"));
  ok("no _writeStr (no string params)", !ts.includes("_writeStr"));
  ok("no _readStr (no string return)", !ts.includes("_readStr"));
  // WASM export names are camelCase (original TS names), not kebab→snake
  contains("add wasm call", ts, `exp["add"]`);
}

