// ── 9. Integration: compile math fixture → modc → bindgen → run host ─────────

async function testIntegrationMath() {
  console.log(yellow(bold("\n── Integration: math_50 compile + bindgen + host")));

  const fixtureSrc = join(FIXTURES, "math_50.ts");
  const fixtureWasm = join(FIXTURES, "math_50.wasm");
  const fixtureWit = join(FIXTURES, "math_50.wit");
  const fixtureBinding = join(FIXTURES, "math_50.bindings.ts");
  const hostRunner = join(FIXTURES, "math_50_host.ts");

  // Step 1: compile TypeScript to WASM library
  const compileResult = await run(WASMTK_BIN, ["modc", fixtureSrc, "-n", fixtureWasm]);
  ok("modc compile succeeded", compileResult.success);
  if (!compileResult.success) {
    console.log(red("    stderr: " + compileResult.stderr.slice(0, 300)));
    return;
  }

  // Step 2: verify WIT file was generated
  let witSrc = "";
  try {
    witSrc = await Deno.readTextFile(fixtureWit);
  } catch { /**/ }
  ok(".wit file generated", witSrc.length > 0);
  ok(".wit has export add", witSrc.includes("export add:"));
  ok(".wit has export multiply", witSrc.includes("export multiply:"));

  // Step 3: generate bindings directly from WIT
  const ts = generateBindings(witSrc);
  await Deno.writeTextFile(fixtureBinding, ts);
  ok("binding written", true);

  // Step 4: write and run host test script
  const bindingUrl = toFileUrl(fixtureBinding).href;
  const wasmUrl = toFileUrl(fixtureWasm).href;
  const hostSrc = `
// auto-generated host runner for math_50 bindgen test
import { loadModule } from "${bindingUrl}";

const wasmBytes = await Deno.readFile(new URL("${wasmUrl}"));
const m = await loadModule(wasmBytes);
console.log(m.add(3, 4));
console.log(m.multiply(2.5, 4.0));
console.log(m.square(5));
`;
  await Deno.writeTextFile(hostRunner, hostSrc);
  const hostResult = await run("deno", ["run", "--allow-read", hostRunner]);
  ok("host runner succeeded", hostResult.success);
  if (!hostResult.success) {
    console.log(red("    stderr: " + hostResult.stderr.slice(0, 300)));
  }
  const lines = hostResult.stdout.trim().split("\n");
  ok("add(3,4) = 7", lines[0]?.trim() === "7");
  ok("multiply(2.5,4.0) = 10", lines[1]?.trim() === "10");
  ok("square(5) = 25", lines[2]?.trim() === "25");
}

