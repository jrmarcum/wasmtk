// ── Assertion harness ────────────────────────────────────────────────────────

let passed = 0;
let failed = 0;

function ok(desc: string, cond: boolean) {
  if (cond) {
    console.log(green(`  ✓ ${desc}`));
    passed++;
  } else {
    console.log(red(`  ✗ ${desc}`));
    failed++;
  }
}

function contains(desc: string, haystack: string, needle: string) {
  ok(desc, haystack.includes(needle));
}

// ── Helper: run subprocess ───────────────────────────────────────────────────

async function run(
  cmd: string,
  args: string[],
): Promise<{ success: boolean; stdout: string; stderr: string }> {
  const result = await new Deno.Command(cmd, {
    args,
    stdout: "piped",
    stderr: "piped",
  }).output();
  const dec = new TextDecoder();
  return {
    success: result.success,
    stdout: dec.decode(result.stdout),
    stderr: dec.decode(result.stderr),
  };
}

