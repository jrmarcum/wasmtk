// math.ts
function add(a, b) {
  return a + b;
}
function multiply(a, b) {
  return a * b;
}
function divide(a, b) {
  return a / b;
}
function subtract(a, b) {
  return a - b;
}
function main() {
  console.log(`Sum: ${add(5, 6)}`);
  console.log(`Product: ${multiply(4, 5)}`);
  console.log(`Quotient: ${divide(30, 2)}`);
  console.log(`Difference: ${subtract(20, 3)}`);
}
main();
