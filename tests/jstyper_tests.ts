// ── Minimal assertion harness ─────────────────────────────────────────────────

let passed = 0;
let failed = 0;

function ok(desc: string, cond: boolean) {
  if (cond) {
    console.log(green(`  ✓ ${desc}`));
    passed++;
  } else {
    console.log(red(`  ✗ ${desc}`));
    failed++;
  }
}

// ── parseJsFunctions ─────────────────────────────────────────────────────────

function testParseJsFunctions() {
  console.log(yellow(bold("\n── parseJsFunctions")));

  const src = `
export function add(a, b) {
  return a + b;
}

function square(x) {
  return x * x;
}

export const lerp = (a, b, t) => {
  return a + (b - a) * t;
};
`;
  const fns = parseJsFunctions(src);
  ok("finds 3 functions", fns.length === 3);
  ok("add: exported, name correct", fns[0].isExported && fns[0].name === "add");
  ok("add: params [a, b]", JSON.stringify(fns[0].params) === '["a","b"]');
  ok("add: body contains return", fns[0].body.includes("return a + b"));
  ok("square: not exported", !fns[1].isExported && fns[1].name === "square");
  ok("lerp: exported arrow", fns[2].isExported && fns[2].name === "lerp");
  ok("lerp: params [a, b, t]", JSON.stringify(fns[2].params) === '["a","b","t"]');
  ok("lerp: body is braced block", fns[2].body.startsWith("{") && fns[2].body.endsWith("}"));
}

function testParseJsFunctionsArrowExpr() {
  console.log(yellow(bold("\n── parseJsFunctions — expression-body arrow")));

  const src = `export const double = (x) => x * 2;\n`;
  const fns = parseJsFunctions(src);
  ok("finds arrow expr function", fns.length === 1 && fns[0].name === "double");
  ok("body wrapped in braces", fns[0].body.includes("{") && fns[0].body.includes("return x * 2"));
}

function testParseJsFunctionsNested() {
  console.log(yellow(bold("\n── parseJsFunctions — nested braces")));

  const src = `
export function clamp(v, lo, hi) {
  if (v < lo) { return lo; }
  if (v > hi) { return hi; }
  return v;
}
`;
  const fns = parseJsFunctions(src);
  ok("finds clamp", fns.length === 1 && fns[0].name === "clamp");
  ok("body includes all branches", fns[0].body.includes("return lo") && fns[0].body.includes("return hi") && fns[0].body.includes("return v"));
}

// ── parseDtsFunctions ─────────────────────────────────────────────────────────

function testParseDtsFunctions() {
  console.log(yellow(bold("\n── parseDtsFunctions")));

  const dts = `
export declare function add(a: i32, b: i32): i32;
export declare function area(w: f64, h: f64): f64;
declare function secret(x: string): void;
`;
  const fns = parseDtsFunctions(dts);
  ok("finds 3 declarations", fns.length === 3);
  ok("add: i32 params", fns[0].params[0].type === "i32" && fns[0].params[1].type === "i32");
  ok("add: i32 return", fns[0].returnType === "i32");
  ok("area: f64 params", fns[1].params[0].type === "f64" && fns[1].params[1].type === "f64");
  ok("area: f64 return", fns[1].returnType === "f64");
  ok("secret: string param", fns[2].params[0].type === "string");
  ok("secret: void return", fns[2].returnType === "void");
}

