async function testDryRun() {
  console.log(yellow(bold("\n── runJstyper --dry-run")));

  const jsPath = join(FIXTURES, "basicmath.js");
  const wouldWrite = jsPath.replace(/\.js$/, ".ts");
  try { await Deno.remove(wouldWrite); } catch { /* ok */ }

  await runJstyper(jsPath, { dryRun: true });

  let exists = false;
  try { await Deno.stat(wouldWrite); exists = true; } catch { /* expected */ }
  ok("dry-run: .ts file not written", !exists);
}

