// ── generateTypedTs ───────────────────────────────────────────────────────────

function testGenerateTypedTsBasic() {
  console.log(yellow(bold("\n── generateTypedTs — basic i32/f64")));

  const jsFns = parseJsFunctions(`
export function add(a, b) {
  return a + b;
}
`);
  const dtsFns = parseDtsFunctions(`export declare function add(a: i32, b: i32): i32;\n`);
  const { source, warnings } = generateTypedTs(jsFns, dtsFns, "warn");
  ok("no warnings", warnings.length === 0);
  ok("signature has i32 types", source.includes("function add(a: i32, b: i32): i32"));
  ok("body preserved", source.includes("return a + b"));
  ok("export keyword present", source.includes("export function add"));
}

function testGenerateTypedTsNumberMapping() {
  console.log(yellow(bold("\n── generateTypedTs — number→f64 mapping")));

  const jsFns = parseJsFunctions(`export function area(w, h) { return w * h; }\n`);
  const dtsFns = parseDtsFunctions(`export declare function area(w: number, h: number): number;\n`);
  const { source, warnings } = generateTypedTs(jsFns, dtsFns, "warn");
  ok("params mapped to f64", source.includes("w: f64") && source.includes("h: f64"));
  ok("return mapped to f64", source.includes("): f64"));
  ok("no warnings for number type", warnings.length === 0);
}

function testGenerateTypedTsMissingDeclaration() {
  console.log(yellow(bold("\n── generateTypedTs — missing .d.ts entry")));

  const jsFns = parseJsFunctions(`
export function known(a) { return a; }
export function unknown(b) { return b; }
`);
  const dtsFns = parseDtsFunctions(`export declare function known(a: i32): i32;\n`);
  const { source, warnings } = generateTypedTs(jsFns, dtsFns, "warn");
  ok("known: included", source.includes("function known"));
  ok("unknown: excluded", !source.includes("function unknown"));
  ok("warning for missing declaration", warnings.some((w) => w.includes("no declaration") && w.includes("unknown")));
}

